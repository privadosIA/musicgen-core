"""
Generates src/MusicGen.Core/Text/PythonTextData.cs from tests/fixtures/lower_reference.json (exhaustive dump of Python 3.11's `str.lower()` /
Unicode 14.0, produced by HeartMuLa.Net's tools/dump_text_reference.py; the fixture here is a byte-identical copy, see tests/fixtures/MANIFEST.md). It only uses the standard library: no venv needed.

The tables give PythonText.Lower Python 3.11's exact result on any platform, without depending on the system's ICU version.

Usage:
    python3 tools/gen_python_text_data.py
"""
import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "tests" / "fixtures" / "lower_reference.json"
DST = REPO / "src" / "MusicGen.Core" / "Text" / "PythonTextData.cs"


def wrap(values, per_line=16, indent="        "):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append(indent + ", ".join(str(v) for v in values[i:i + per_line]))
    return ",\n".join(lines)


def main():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    single, multi = [], []
    for cp, low in d["lower_diff"]:
        (single if len(low) == 1 else multi).append((cp, low))
    assert [cp for cp, _ in multi] == [0x130], f"expected only U+0130 as a multi-character lowercase, found: {multi}"
    assert [cp for cp, _ in single] == sorted(cp for cp, _ in single), "lower_diff is not sorted"

    pairs = [v for cp, low in single for v in (cp, low[0])]
    cased = [v for a, b in d["cased_nonignorable_ranges"] for v in (a, b)]
    ign = [v for a, b in d["case_ignorable_ranges"] for v in (a, b)]

    out = f'''// <auto-generated>
// Generated by tools/gen_python_text_data.py from tests/fixtures/lower_reference.json. DO NOT EDIT BY HAND: regenerate.
// Origin: Python {d["python"]} `str.lower()` (Unicode {d["unicode"]}), exhaustive walk over {d["code_points_checked"]} code points.
// </auto-generated>
namespace MusicGen.Core.Text;

internal static class PythonTextData
{{
    internal const string PythonVersion = "{d["python"]}";
    internal const string UnicodeVersion = "{d["unicode"]}";

    /// <summary>Simple lowercase mappings: (code point, lowercase) pairs sorted by code point. {len(single)} pairs.</summary>
    internal static readonly int[] LowerPairs =
    {{
{wrap(pairs)}
    }};

    /// <summary>Multi-character lowercase mappings: only U+0130, which does not depend on the language.</summary>
    internal static readonly (int From, int[] To)[] LowerMulti =
    {{
        ({multi[0][0]}, new[] {{ {", ".join(str(x) for x in multi[0][1])} }}),
    }};

    /// <summary>[start, end] ranges (flattened) of cased letters that are NOT case-ignorable, as CPython uses them for the final sigma. {len(cased) // 2} ranges.</summary>
    internal static readonly int[] CasedNonIgnorableRanges =
    {{
{wrap(cased)}
    }};

    /// <summary>[start, end] ranges (flattened) of case-ignorable characters, as CPython uses them for the final sigma. {len(ign) // 2} ranges.</summary>
    internal static readonly int[] CaseIgnorableRanges =
    {{
{wrap(ign)}
    }};
}}
'''
    DST.write_text(out, encoding="utf-8")
    print(f"wrote {DST.relative_to(REPO)}: {len(single)} simple lowercase mappings, 1 multi-character, {len(cased)//2} Cased ranges, {len(ign)//2} Case_Ignorable ranges ({DST.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
